/**
 * Сессия живёт год, а не пять дней.
 *
 * В миграции 1786803000 записано, что личная ссылка «логинит навсегда», —
 * и это было неправдой: срок токена остался дефолтным, 432000 секунд
 * (5 дней). Дальше сценарий такой: человек вошёл, позанимался, уехал
 * на неделю, вернулся — и он снова аноним. Сайт при этом работает как
 * ни в чём не бывало, прогресс молча копится в localStorage, а в базе
 * пусто. Именно так и вышло: у Will'а в базе не оказалось ни одной
 * записи повторений, хотя занимался он много.
 *
 * Год — не «побольше на всякий случай», а прямое следствие того, чем
 * ссылка задумана: постоянным ключом, который открывают на телефоне
 * и на ноуте и больше о нём не думают. Токен и так долгоживущий секрет
 * в адресе (см. компромисс в pb_hooks/invite.pb.js); срок сессии здесь
 * ничего не охраняет, а только выкидывает своего же человека.
 * Отзыв по-прежнему в один клик: очистить invite_token в админке —
 * хук выпишет новый, старая ссылка умрёт.
 *
 * Заодно чиним appURL: он остался localhost:8090 с первого запуска.
 */
migrate((app) => {
  const users = app.findCollectionByNameOrId('users');
  users.authToken.duration = 365 * 24 * 60 * 60;   // 31 536 000 с
  app.save(users);

  const settings = app.settings();
  settings.meta.appName = 'langlab';
  settings.meta.appURL = 'https://langs.crs-projects.com';
  app.save(settings);

  console.log('[migration] сессия пользователя: 5 дней → год');
}, (app) => {
  const users = app.findCollectionByNameOrId('users');
  users.authToken.duration = 5 * 24 * 60 * 60;
  app.save(users);
});
